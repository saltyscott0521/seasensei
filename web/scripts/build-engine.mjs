// Bundles the app's pure forecast logic (src/lib/briefing.ts and what it imports: session, sensei, wind, forecast,
// marine, widget) into server/engine.mjs, so the server's morning briefing and home-screen widget say exactly what the
// board says. Runs on
// `prebuild` (and before the server end-to-end tests); the Dockerfile copies the result into the runtime image.
// No React or browser modules may end up in it: the build fails if one does.
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = await build({
  absWorkingDir: root,
  entryPoints: ["src/lib/briefing.ts"],
  outfile: "server/engine.mjs",
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  legalComments: "none",
  banner: { js: "// GENERATED by scripts/build-engine.mjs from src/lib/briefing.ts. Do not edit; run `npm run build:engine`." },
  metafile: true,
  write: false, // written below, atomically: a server starting meanwhile never reads half a file
  logLevel: "warning",
});
const file = path.join(root, "server/engine.mjs"), tmp = `${file}.${process.pid}.tmp`;
fs.writeFileSync(tmp, out.outputFiles[0].contents);
fs.renameSync(tmp, file);
const inputs = Object.keys(out.metafile.inputs);
const foreign = inputs.filter((f) => !f.startsWith("src/lib/"));
if (foreign.length) throw new Error(`engine bundle pulled in non-engine modules: ${foreign.join(", ")}`);
console.log(`engine → server/engine.mjs (${inputs.map((f) => f.replace("src/lib/", "")).join(", ")})`);
